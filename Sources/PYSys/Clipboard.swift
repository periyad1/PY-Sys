import AppKit
import SwiftUI

// MARK: - Riwayat clipboard

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image, files }
    let id: String
    let kind: Kind
    let text: String            // teks, atau daftar path untuk files
    let imagePNG: Data?
    let app: String?
    let date: Date
    var pinned: Bool

    var preview: String {
        switch kind {
        case .text: return text.trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "\n", with: " ⏎ ")
        case .image: return tr("Gambar", "Image")
        case .files: return text.split(separator: "\n").map { ($0 as NSString).lastPathComponent }.joined(separator: ", ")
        }
    }
}

final class ClipboardHistory: NSObject, ObservableObject {
    static let shared = ClipboardHistory()

    @Published var enabled: Bool { didSet { UserDefaults.standard.set(enabled, forKey: "clipEnabled"); enabled ? start() : stop() } }
    @Published var maxItems: Int { didSet { UserDefaults.standard.set(maxItems, forKey: "clipMax"); trim() } }
    @Published var autoPaste: Bool { didSet { UserDefaults.standard.set(autoPaste, forKey: "clipAutoPaste") } }
    @Published var keepImages: Bool { didSet { UserDefaults.standard.set(keepImages, forKey: "clipImages") } }
    @Published private(set) var items: [ClipItem] = []
    @Published var search = ""

    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var installed = false
    private var lastFront: NSRunningApplication?

    /// Pengelola password & app sensitif menandai isinya; tidak disimpan.
    private static let concealed: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]

    private var pinURL: URL {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("PY-Sys", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir.appendingPathComponent("clipboard-pins.json")
    }

    override init() {
        let d = UserDefaults.standard
        enabled = d.bool(forKey: "clipEnabled")
        maxItems = d.object(forKey: "clipMax") as? Int ?? 40
        autoPaste = d.object(forKey: "clipAutoPaste") as? Bool ?? true
        keepImages = d.object(forKey: "clipImages") as? Bool ?? true
        super.init()
        let dec = JSONDecoder()
        dec.dateDecodingStrategy = .secondsSince1970
        if let data = try? Data(contentsOf: pinURL), let p = try? dec.decode([ClipItem].self, from: data) { items = p }
    }

    func start() {
        guard enabled else { return }
        if timer == nil {
            lastChange = NSPasteboard.general.changeCount
            let t = Timer(timeInterval: 1.5, repeats: true) { [weak self] _ in self?.poll() }
            t.tolerance = 0.5
            RunLoop.main.add(t, forMode: .common)
            timer = t
        }
        if !installed {
            installed = true
            HotkeyCenter.shared.handlers.append { code, flags in
                guard ClipboardHistory.shared.enabled, code == Key.v, flags == [.maskControl, .maskAlternate] else { return false }
                DispatchQueue.main.async { ClipboardHistory.shared.showMenu() }
                return true
            }
        }
        HotkeyCenter.shared.ensure(prompt: false)
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = pb.types ?? []
        if types.contains(where: { Self.concealed.contains($0) }) { return }
        let app = NSWorkspace.shared.frontmostApplication
        guard app?.bundleIdentifier != Bundle.main.bundleIdentifier else { return }   // tempelan dari PY-Sys sendiri

        var item: ClipItem?
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            item = ClipItem(id: UUID().uuidString, kind: .files, text: urls.map(\.path).joined(separator: "\n"),
                            imagePNG: nil, app: app?.localizedName, date: Date(), pinned: false)
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            item = ClipItem(id: UUID().uuidString, kind: .text, text: String(s.prefix(20_000)),
                            imagePNG: nil, app: app?.localizedName, date: Date(), pinned: false)
        } else if keepImages, let img = NSImage(pasteboard: pb), let png = Self.png(img, maxSide: 1600), png.count < 6_000_000 {
            item = ClipItem(id: UUID().uuidString, kind: .image, text: "", imagePNG: png,
                            app: app?.localizedName, date: Date(), pinned: false)
        }
        guard let new = item else { return }
        // Hapus duplikat teks yang sama, taruh yang baru di atas
        if new.kind == .text, let i = items.firstIndex(where: { $0.kind == .text && $0.text == new.text }) {
            let old = items.remove(at: i)
            items.insert(ClipItem(id: old.id, kind: .text, text: old.text, imagePNG: nil, app: new.app, date: Date(), pinned: old.pinned), at: 0)
        } else {
            items.insert(new, at: 0)
        }
        trim()
    }

    private static func png(_ img: NSImage, maxSide: CGFloat) -> Data? {
        let s = img.size
        guard s.width > 0, s.height > 0 else { return nil }
        let k = min(1, maxSide / max(s.width, s.height))
        let size = NSSize(width: (s.width * k).rounded(), height: (s.height * k).rounded())
        guard let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: Int(size.width), pixelsHigh: Int(size.height),
                                         bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                         colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0) else { return nil }
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
        img.draw(in: NSRect(origin: .zero, size: size))
        NSGraphicsContext.restoreGraphicsState()
        return rep.representation(using: .png, properties: [:])
    }

    private func trim() {
        var unpinned = 0
        var images = 0
        items = items.filter { it in
            if it.pinned { return true }
            unpinned += 1
            if it.kind == .image { images += 1; if images > 10 { return false } }
            return unpinned <= maxItems
        }
    }

    // MARK: Aksi

    func copy(_ it: ClipItem, paste: Bool) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch it.kind {
        case .text: pb.setString(it.text, forType: .string)
        case .image: if let d = it.imagePNG { pb.setData(d, forType: .png) }
        case .files: pb.writeObjects(it.text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) as NSURL })
        }
        lastChange = pb.changeCount
        if let i = items.firstIndex(of: it), !it.pinned {
            let x = items.remove(at: i)
            items.insert(x, at: 0)
        }
        guard paste, autoPaste, AXIsProcessTrusted() else { return }
        // Kembali ke app sebelumnya, lalu kirim ⌘V
        lastFront?.activate(options: [])
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            let src = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let e = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(Key.v), keyDown: down)
                e?.flags = .maskCommand
                e?.post(tap: .cghidEventTap)
            }
        }
    }

    func togglePin(_ it: ClipItem) {
        guard let i = items.firstIndex(of: it) else { return }
        items[i].pinned.toggle()
        savePins()
    }

    func delete(_ it: ClipItem) {
        items.removeAll { $0.id == it.id }
        savePins()
    }

    func clear(keepPinned: Bool = true) {
        items = keepPinned ? items.filter(\.pinned) : []
        savePins()
    }

    /// Hanya item yang disematkan yang disimpan ke disk; sisanya hilang saat PY-Sys ditutup.
    private func savePins() {
        let enc = JSONEncoder()
        enc.dateEncodingStrategy = .secondsSince1970
        if let d = try? enc.encode(items.filter(\.pinned)) { try? d.write(to: pinURL, options: .atomic) }
    }

    // MARK: Menu ⌃⌥V di posisi kursor

    private var menuItems: [ClipItem] = []

    func showMenu() {
        lastFront = NSWorkspace.shared.frontmostApplication
        let m = NSMenu(title: "Clipboard")
        m.autoenablesItems = false
        let list = Array((items.filter(\.pinned) + items.filter { !$0.pinned }).prefix(20))
        menuItems = list
        if list.isEmpty {
            let e = NSMenuItem(title: tr("Riwayat clipboard masih kosong", "Clipboard history is empty"), action: nil, keyEquivalent: "")
            e.isEnabled = false
            m.addItem(e)
        }
        for (i, it) in list.enumerated() {
            let title = String(it.preview.prefix(60)) + (it.preview.count > 60 ? "…" : "")
            let mi = NSMenuItem(title: title, action: #selector(pick(_:)), keyEquivalent: i < 9 ? "\(i + 1)" : "")
            mi.keyEquivalentModifierMask = []
            mi.target = self
            mi.tag = i
            if it.pinned { mi.image = NSImage(systemSymbolName: "pin.fill", accessibilityDescription: nil) }
            if it.kind == .image, let d = it.imagePNG, let img = NSImage(data: d) {
                img.size = NSSize(width: 28 * img.size.width / max(img.size.height, 1), height: 28)
                mi.image = img
            }
            if it.kind == .files { mi.image = NSImage(systemSymbolName: "doc", accessibilityDescription: nil) }
            m.addItem(mi)
        }
        m.addItem(.separator())
        let open = NSMenuItem(title: tr("Buka riwayat di PY-Sys…", "Open history in PY-Sys…"), action: #selector(openTab), keyEquivalent: "")
        open.target = self
        m.addItem(open)
        NSApp.activate(ignoringOtherApps: true)
        _ = m.popUp(positioning: nil, at: NSEvent.mouseLocation, in: nil)
    }

    @objc private func pick(_ s: NSMenuItem) {
        guard s.tag < menuItems.count else { return }
        copy(menuItems[s.tag], paste: true)
    }

    @objc private func openTab() {
        UIState.shared.tab = AppTab.clipboard.rawValue
        Notifier.post(title: "PY-Sys", body: tr("Klik ikon PY-Sys di menu bar untuk melihat riwayat clipboard.",
                                                "Click the PY-Sys menu bar icon to see the clipboard history."))
    }
}

struct ClipboardTab: View {
    @ObservedObject private var ch = ClipboardHistory.shared
    @ObservedObject private var hc = HotkeyCenter.shared

    private var shown: [ClipItem] {
        let base = ch.items.filter(\.pinned) + ch.items.filter { !$0.pinned }
        guard !ch.search.isEmpty else { return base }
        return base.filter { $0.preview.localizedCaseInsensitiveContains(ch.search) }
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            Toggle(tr("Aktifkan riwayat clipboard", "Enable clipboard history"), isOn: $ch.enabled).toggleStyle(.switch)
            Text(tr("⌃⌥V (Control + Option + V) membuka riwayat di posisi kursor. Tekan 1–9 untuk memilih cepat.",
                    "⌃⌥V (Control + Option + V) opens the history at the pointer. Press 1–9 to pick quickly."))
                .font(.caption).foregroundStyle(.secondary).fixedSize(horizontal: false, vertical: true)

            if ch.enabled {
                TextField(tr("Cari…", "Search…"), text: $ch.search).textFieldStyle(.roundedBorder)
                if shown.isEmpty {
                    Text(tr("Belum ada yang disalin sejak riwayat diaktifkan.", "Nothing copied since the history was turned on."))
                        .font(.caption).foregroundStyle(.secondary)
                }
                ForEach(shown) { it in
                    HStack(alignment: .top, spacing: 8) {
                        Group {
                            if it.kind == .image, let d = it.imagePNG, let img = NSImage(data: d) {
                                Image(nsImage: img).resizable().scaledToFit().frame(width: 44, height: 30)
                            } else {
                                Image(systemName: it.kind == .files ? "doc" : "text.alignleft").frame(width: 44)
                                    .foregroundStyle(.secondary)
                            }
                        }
                        VStack(alignment: .leading, spacing: 1) {
                            Text(it.preview).lineLimit(2).font(.caption)
                            Text((it.app ?? "") + " · " + it.date.formatted(date: .omitted, time: .shortened))
                                .font(.caption2).foregroundStyle(.secondary)
                        }
                        Spacer()
                        Button { ch.copy(it, paste: false) } label: { Image(systemName: "doc.on.doc") }
                            .buttonStyle(.borderless).help(tr("Salin", "Copy"))
                        Button { ch.togglePin(it) } label: { Image(systemName: it.pinned ? "pin.fill" : "pin") }
                            .buttonStyle(.borderless).help(tr("Sematkan (disimpan permanen)", "Pin (kept permanently)"))
                        Button { ch.delete(it) } label: { Image(systemName: "xmark") }
                            .buttonStyle(.borderless)
                    }
                    Divider()
                }
                HStack {
                    Button(tr("Hapus semua (kecuali yang disematkan)", "Clear all (except pinned)")) { ch.clear() }
                        .controlSize(.small)
                    Spacer()
                }
            }

            GroupBox(tr("Pengaturan", "Settings")) {
                VStack(alignment: .leading, spacing: 6) {
                    Stepper(tr("Simpan \(ch.maxItems) item terakhir", "Keep the last \(ch.maxItems) items"), value: $ch.maxItems, in: 10...200, step: 10)
                    Toggle(tr("Langsung tempel setelah memilih dari menu ⌃⌥V", "Paste right after picking from the ⌃⌥V menu"), isOn: $ch.autoPaste)
                    Toggle(tr("Simpan gambar (maks. 10)", "Keep images (max. 10)"), isOn: $ch.keepImages)
                    Text(tr("Riwayat disimpan di memori saja dan hilang saat PY-Sys ditutup, kecuali item yang disematkan. Isi dari pengelola password (1Password, Bitwarden, Keychain) tidak dicatat.",
                            "History lives in memory only and is cleared when PY-Sys quits, except pinned items. Content from password managers (1Password, Bitwarden, Keychain) is not recorded."))
                        .font(.caption2).foregroundStyle(.secondary).fixedSize(horizontal: false, vertical: true)
                }
                .font(.caption)
            }
            if let m = hc.message { Text(m).font(.caption).foregroundStyle(.orange) }
        }
    }
}
